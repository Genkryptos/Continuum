"""
evals/audit/convertibility.py
=============================
**P5 of `evals/PREREGISTRATION.md`** — the gate on S1–S3.

Question: what fraction of LongMemEval's ``temporal-reasoning`` questions can be
answered by *executing a typed query* over Continuum's temporal algebra
(``as_of`` / ``timeline`` / count / date-arithmetic) instead of by asking the
answerer to reason?

The pre-registered threshold is **≥ 40% convertible**. Below that, the
typed-query lever is weaker than `docs/SMALL_MODEL_ACCURACY.md` assumes and
S1–S3 must be re-scoped *before* being built.

Usage
-----
.. code-block:: bash

    # 1. emit the classification sheet (deterministic; seed pinned)
    python3 -m evals.audit.convertibility --emit

    # 2. fill in the `bucket` column by hand, then:
    python3 -m evals.audit.convertibility --score

Design
------
Two modes so the audit is *reproducible* rather than hand-tallied: the same
sample is regenerated by anyone with the repo, and the verdict is computed from
the filled sheet rather than counted by eye. The sheet carries its own provenance
header (dataset, seed, n) so a stale sheet cannot be silently re-scored.

The classification itself is deliberately **human** — an LLM classifying whether
an LLM can avoid reasoning is circular, and this number gates 20h of work.
"""

from __future__ import annotations

import argparse
import csv
import json
import random
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
_DATASET = _HERE.parent / "longmemeval" / "LongMemEval" / "data" / "longmemeval_s_cleaned.json"
_SHEET = _HERE / "convertibility_sheet.csv"

QUESTION_TYPE = "temporal-reasoning"
SAMPLE_N = 50
SEED = 0
THRESHOLD = 0.40

#: Buckets, derived from inspecting the actual question set (not invented).
#: The first four are *convertible* — a typed query plus deterministic
#: arithmetic answers them without the model reasoning about dates.
BUCKETS: dict[str, str] = {
    "date_diff": (
        "Interval between two located events. 'How many days passed between X "
        "and Y', 'How long had I been doing X when Y happened', 'How old was I "
        "when Z'. → timeline lookup of two anchors, then subtract."
    ),
    "ordering": (
        "Which of two or more events came first / the sequence. → timeline "
        "lookup, then min/sort."
    ),
    "as_of_lookup": (
        "Resolve a relative date against question_date, then retrieve what "
        "happened at/near it. 'What did I mention four weeks ago', 'who gave me "
        "the jewelry last Saturday'. → as_of query."
    ),
    "absence": (
        "The gold answer is 'not enough information'. → a query returning zero "
        "rows is deterministic evidence of absence, where a model would "
        "hallucinate."
    ),
    "not_convertible": (
        "Needs genuine semantic or multi-hop reasoning that no date operation "
        "captures. This is the honest bucket — use it freely."
    ),
    "unsure": "Needs a second look. Resolve before scoring; --score rejects these.",
}

CONVERTIBLE = ("date_diff", "ordering", "as_of_lookup", "absence")

_FIELDS = ["idx", "question_id", "question_date", "bucket", "question", "gold_answer", "notes"]


def _load_sample() -> list[dict]:
    if not _DATASET.exists():
        sys.exit(
            f"dataset not found: {_DATASET}\n"
            "run: cd evals/longmemeval && python setup.py"
        )
    rows = json.loads(_DATASET.read_text())
    pool = [r for r in rows if r.get("question_type") == QUESTION_TYPE]
    if len(pool) < SAMPLE_N:
        sys.exit(f"only {len(pool)} {QUESTION_TYPE} rows; need {SAMPLE_N}")
    rng = random.Random(SEED)
    return rng.sample(pool, SAMPLE_N)


def emit() -> int:
    """Write the blank classification sheet. Refuses to clobber a filled one."""
    if _SHEET.exists():
        existing = list(csv.DictReader(_SHEET.open()))
        filled = sum(1 for r in existing if r.get("bucket", "").strip())
        if filled:
            sys.exit(
                f"{_SHEET} already has {filled} classified row(s) — refusing to "
                "overwrite. Delete it explicitly if you want a fresh sheet."
            )

    sample = _load_sample()
    _SHEET.parent.mkdir(parents=True, exist_ok=True)
    with _SHEET.open("w", newline="") as fh:
        fh.write(f"# dataset={_DATASET.name} type={QUESTION_TYPE} n={SAMPLE_N} seed={SEED}\n")
        fh.write(f"# buckets: {' | '.join(BUCKETS)}\n")
        fh.write(f"# convertible = {', '.join(CONVERTIBLE)}; threshold = {THRESHOLD:.0%}\n")
        w = csv.DictWriter(fh, fieldnames=_FIELDS)
        w.writeheader()
        for i, r in enumerate(sample, 1):
            w.writerow(
                {
                    "idx": i,
                    "question_id": r.get("question_id", ""),
                    "question_date": r.get("question_date", ""),
                    "bucket": "",
                    "question": " ".join(r["question"].split()),
                    "gold_answer": " ".join(str(r.get("answer", "")).split()),
                    "notes": "",
                }
            )

    print(f"wrote {_SHEET} — {SAMPLE_N} rows, seed {SEED}\n")
    print("Buckets:")
    for name, desc in BUCKETS.items():
        mark = "✓" if name in CONVERTIBLE else " "
        print(f"  [{mark}] {name}\n        {desc}")
    print("\nFill the `bucket` column, then: python3 -m evals.audit.convertibility --score")
    return 0


def score() -> int:
    """Read the filled sheet and report the convertible fraction vs threshold."""
    if not _SHEET.exists():
        sys.exit(f"no sheet at {_SHEET} — run --emit first")

    rows = [r for r in csv.DictReader(line for line in _SHEET.open() if not line.startswith("#"))]
    buckets = [(r["idx"], (r.get("bucket") or "").strip()) for r in rows]

    blank = [i for i, b in buckets if not b]
    unsure = [i for i, b in buckets if b == "unsure"]
    unknown = sorted({b for _, b in buckets if b and b not in BUCKETS})

    if unknown:
        sys.exit(f"unknown bucket(s): {unknown}\nvalid: {list(BUCKETS)}")
    if blank:
        sys.exit(f"{len(blank)} unclassified row(s): {', '.join(blank)}")
    if unsure:
        sys.exit(f"{len(unsure)} row(s) still 'unsure': {', '.join(unsure)} — resolve before scoring")

    counts: dict[str, int] = {k: 0 for k in BUCKETS}
    for _, b in buckets:
        counts[b] += 1

    n = len(buckets)
    conv = sum(counts[k] for k in CONVERTIBLE)
    frac = conv / n

    print(f"n = {n}   (dataset {_DATASET.name}, {QUESTION_TYPE}, seed {SEED})\n")
    for k in BUCKETS:
        if k == "unsure":
            continue
        mark = "✓" if k in CONVERTIBLE else " "
        print(f"  [{mark}] {k:<16} {counts[k]:>3}  {counts[k] / n:>6.1%}")
    print(f"\n  convertible      {conv:>3}  {frac:>6.1%}   (threshold {THRESHOLD:.0%})")

    if frac >= THRESHOLD:
        print("\nP5 HOLDS — the typed-query lever is worth building. Proceed to S1.")
        return 0
    print(
        "\nP5 FALSIFIED — below threshold. Per the pre-registration, STOP and "
        "re-scope S1–S3 before building.\nThis is a legitimate finding: record it, "
        "do not quietly lower the threshold."
    )
    return 1


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument("--emit", action="store_true", help="write the blank classification sheet")
    g.add_argument("--score", action="store_true", help="score the filled sheet against the threshold")
    args = p.parse_args(argv)
    return emit() if args.emit else score()


if __name__ == "__main__":
    raise SystemExit(main())
